import os
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.shapes import MSO_SHAPE
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas

DESKTOP_DIR = os.path.join(os.path.expanduser("~"), "Desktop")

def hex_to_rgb(hex_str: str) -> RGBColor:
    hex_str = hex_str.lstrip('#')
    return RGBColor(*(int(hex_str[i:i+2], 16) for i in (0, 2, 4)))

def create_styled_presentation(
    title: str, 
    theme: dict, 
    slides: list[dict], 
    filename: str = "Custom_Presentation.pptx"
) -> str:
    """
    Creates presentations driven entirely by dynamic design tokens.
    theme: {
        "bg_hex": "#0b0c10",
        "card_hex": "#1f2833",
        "accent_hex": "#66fcf1",
        "text_hex": "#c5c6c7",
        "font_name": "Segoe UI"
    }
    """
    prs = Presentation()
    bg_col = hex_to_rgb(theme.get("bg_hex", "#1e1e24"))
    card_col = hex_to_rgb(theme.get("card_hex", "#2d2d35"))
    acc_col = hex_to_rgb(theme.get("accent_hex", "#00c8ff"))
    txt_col = hex_to_rgb(theme.get("text_hex", "#f0f0f0"))
    font_name = theme.get("font_name", "Arial")

    # --- Title Slide ---
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = bg_col

    tb = slide.shapes.add_textbox(Inches(1), Inches(2.5), Inches(8), Inches(1.5))
    p = tb.text_frame.paragraphs[0]
    p.text = title
    p.font.name = font_name
    p.font.size = Pt(44)
    p.font.bold = True
    p.font.color.rgb = acc_col

    # --- Dynamic Content Slides ---
    for sc in slides:
        s = prs.slides.add_slide(prs.slide_layouts[6])
        s.background.fill.solid()
        s.background.fill.fore_color.rgb = bg_col

        # Title
        t_box = s.shapes.add_textbox(Inches(0.8), Inches(0.5), Inches(8.4), Inches(0.8))
        tp = t_box.text_frame.paragraphs[0]
        tp.text = sc.get("title", "")
        tp.font.name = font_name
        tp.font.size = Pt(28)
        tp.font.bold = True
        tp.font.color.rgb = acc_col

        layout_type = sc.get("layout", "card_stack")

        if layout_type == "columns":
            # Multi-column grid layout (e.g. 2 or 3 distinct cards side by side)
            items = sc.get("items", [])
            col_width = Inches(8.4 / max(len(items), 1))
            for i, col_data in enumerate(items):
                left = Inches(0.8) + (i * col_width) + Inches(0.1)
                box = s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, left, Inches(1.8), col_width - Inches(0.2), Inches(4.8))
                box.fill.solid()
                box.fill.fore_color.rgb = card_col
                box.line.color.rgb = acc_col
                
                tf = box.text_frame
                tf.word_wrap = True
                p_head = tf.paragraphs[0]
                p_head.text = col_data.get("header", "")
                p_head.font.name = font_name
                p_head.font.bold = True
                p_head.font.size = Pt(16)
                p_head.font.color.rgb = acc_col
                
                for pt in col_data.get("points", []):
                    p_pt = tf.add_paragraph()
                    p_pt.text = f"• {pt}"
                    p_pt.font.name = font_name
                    p_pt.font.size = Pt(13)
                    p_pt.font.color.rgb = txt_col
        else:
            # Standard single large card layout
            card = s.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(0.8), Inches(1.6), Inches(8.4), Inches(5))
            card.fill.solid()
            card.fill.fore_color.rgb = card_col
            card.line.color.rgb = acc_col
            tf = card.text_frame
            tf.word_wrap = True
            for i, pt in enumerate(sc.get("bullets", [])):
                p = tf.add_paragraph() if i > 0 else tf.paragraphs[0]
                p.text = f"• {pt}"
                p.font.name = font_name
                p.font.size = Pt(18)
                p.font.color.rgb = txt_col
                p.space_after = Pt(12)

    out_path = os.path.join(DESKTOP_DIR, filename)
    prs.save(out_path)
    return f"Custom styled presentation saved to {out_path}"


def create_presentation(title: str, slides: list[dict], filename: str = "Presentation.pptx") -> str:
    """
    Creates a standard PowerPoint presentation and saves it to the Desktop.
    slides format: [{"title": "Slide Title", "bullets": ["Point 1", "Point 2"]}]
    """
    prs = Presentation()

    # Title Slide
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    slide.shapes.title.text = title
    if len(slide.placeholders) > 1:
        slide.placeholders[1].text = "Generated by MAX Agent"

    # Content Slides
    bullet_slide_layout = prs.slide_layouts[1]
    for sc in slides:
        s = prs.slides.add_slide(bullet_slide_layout)
        s.shapes.title.text = sc.get("title", "")
        if len(s.shapes.placeholders) > 1:
            body = s.shapes.placeholders[1]
            tf = body.text_frame
            for i, pt in enumerate(sc.get("bullets", [])):
                p = tf.add_paragraph() if i > 0 else tf.paragraphs[0]
                p.text = pt
                p.level = 0

    out_path = os.path.join(DESKTOP_DIR, filename)
    prs.save(out_path)
    return f"PowerPoint successfully created at: {out_path}"


def create_pdf(title: str, paragraphs: list[str], filename: str = "Document.pdf") -> str:
    """Creates a PDF document and saves it to the Desktop."""
    out_path = os.path.join(DESKTOP_DIR, filename)
    c = canvas.Canvas(out_path, pagesize=letter)
    width, height = letter

    # Header
    c.setFont("Helvetica-Bold", 16)
    c.drawString(50, height - 50, title)
    c.setLineWidth(0.5)
    c.line(50, height - 55, width - 50, height - 55)

    # Paragraphs
    c.setFont("Helvetica", 10)
    y_pos = height - 80
    for para in paragraphs:
        if y_pos < 50:
            c.showPage()
            c.setFont("Helvetica", 10)
            y_pos = height - 50
        c.drawString(50, y_pos, str(para)[:100])
        y_pos -= 20

    c.save()
    return f"PDF document successfully created at: {out_path}"